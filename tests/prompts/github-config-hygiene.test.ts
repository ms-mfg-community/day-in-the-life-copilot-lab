/** True when `name` appears as a whole agent name ("architecture" does not mention `architect`). */
const mentionsAgent = (text: string, name: string): boolean =>
  new RegExp(`(?<![\\w-])${escapeRe(name)}(?![\\w-])`, 'i').test(text);

