describe('Phase 1 files: cited repo paths and relative links resolve', () => {
  /** Concrete `dotnet/...` and `node/...` paths. Wildcards and `{placeholders}` are skipped. */
  function citedPaths(text: string): string[] {
    const out = new Set<string>();
    for (const m of text.matchAll(/(?<![\w./-])(?:dotnet|node)\/[\w.-]+(?:\/[\w.-]+)*/g)) {
      const next = text[(m.index ?? 0) + m[0].length] ?? '';
      if (/[*{<[]/.test(next)) continue;
      out.add(m[0].replace(/[.-]+$/, ''));
    }
    return [...out];
  }

  it.each(PHASE1_FILES)('%s cites only repo paths that exist', (rel) => {
    const missing = citedPaths(read(rel)).filter((p) => !existsSync(join(ROOT, p)));
    expect(missing).toEqual([]);
  });

  it.each(PHASE1_FILES)('%s has no broken relative markdown link', (rel) => {
    const links = [...read(rel).matchAll(/\[[^\]]*\]\(([^)\s]+)\)/g)]
      .map((m) => m[1])
      .filter((target) => !/^(?:[a-z][a-z0-9+.-]*:|#)/i.test(target));
    const broken = links.filter((target) => !existsSync(resolve(dirname(join(ROOT, rel)), target.split('#')[0])));
    expect(broken).toEqual([]);
  });
});

