const escapeRe = (s: string): string => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/**
 * Hand-authored text under `.github/`. Skips `logs/` (gitignored runtime output that
 * records user prompts verbatim) and `*.lock.yml` (generated by `gh aw compile`).
 */
function authoredFiles(dir: string = GITHUB): string[] {
  const out: string[] = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name !== 'logs') out.push(...authoredFiles(full));
    } else if (/\.(?:md|json|ya?ml)$/.test(entry.name) || entry.name === 'CODEOWNERS') {
      if (!entry.name.endsWith('.lock.yml')) out.push(full);
    }
  }
  return out;
}

/** `path:line: text` for every line in `files` that matches `re` (use a non-global regex). */
function occurrences(re: RegExp, files: string[]): string[] {
  const hits: string[] = [];
  for (const file of files) {
    readFileSync(file, 'utf8')
      .split(/\r?\n/)
      .forEach((text, i) => {
        if (re.test(text)) hits.push(`${relative(ROOT, file)}:${i + 1}: ${text.trim()}`);
      });
  }
  return hits;
}

/** Non-blank lines between `heading` and the next `## ` heading. */
function sectionLines(rel: string, heading: string): string[] {
  const all = fileLines(rel);
  const from = all.findIndex((l) => l.trim() === heading);
  expect(from, `${rel} must keep the "${heading}" heading`).toBeGreaterThanOrEqual(0);
  const rest = all.slice(from + 1);
  const end = rest.findIndex((l) => /^##\s/.test(l));
  return (end === -1 ? rest : rest.slice(0, end)).filter((l) => l.trim() !== '');
}

function registryModels(): Set<string> {
  const doc = yaml.load(readFileSync(REGISTRY, 'utf8')) as { models?: Record<string, unknown> };
  const out = new Set<string>();
  for (const value of Object.values(doc.models ?? {})) {
    if (typeof value === 'string') out.add(value.toLowerCase());
    else if (Array.isArray(value)) {
      for (const v of value) if (typeof v === 'string') out.add(v.toLowerCase());
    }
  }
  return out;
}

