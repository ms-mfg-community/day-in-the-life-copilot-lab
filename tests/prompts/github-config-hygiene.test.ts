/** `agent -> Track cell` of the agent table in `rel` (the table whose header row has `Agent` and `Track`). */
function trackColumn(rel: string): Map<string, string> {
  const out = new Map<string, string>();
  let col = -1;
  for (const line of fileLines(rel)) {
    if (!line.trim().startsWith('|')) {
      col = -1;
      continue;
    }
    const cells = line.split('|').slice(1, -1).map((c) => c.trim());
    if (cells[0] === 'Agent') {
      col = cells.indexOf('Track');
      continue;
    }
    const name = cells[0]?.match(/^`([a-z][a-z-]*)`$/)?.[1];
    if (name && col >= 0) out.set(name, cells[col]);
  }
  return out;
}

/** The `.NET:` and `Node:` pipelines (`Node:  planner -> node-dev -> main agent`) in the `### workflow` section of `rel`. */
function pipelines(rel: string, workflow: string): Record<string, string[]> {
  const all = fileLines(rel);
  const from = all.findIndex((l) => l.trim() === `### ${workflow}`);
  expect(from, `${rel} must keep a "### ${workflow}" workflow`).toBeGreaterThanOrEqual(0);
  const rest = all.slice(from + 1);
  const end = rest.findIndex((l) => /^#{2,3}\s/.test(l));
  const out: Record<string, string[]> = {};
  for (const line of end === -1 ? rest : rest.slice(0, end)) {
    const m = line.match(/^(\.NET|Node):\s+(.+)$/);
    if (m) out[m[1]] = m[2].trim().split(' -> ');
  }
  return out;
}

